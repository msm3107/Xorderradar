import { z } from "zod";
import { DomainError } from "./errors.js";

/**
 * Matches a lone UTF-16 surrogate. With the `u` flag a valid surrogate pair is
 * read as one code point, so only unpaired halves match — the same rule as
 * `String.prototype.isWellFormed` (ES2024, not in this project's ES2023 lib).
 * PostgreSQL would silently replace them with U+FFFD in text columns but
 * reject them in jsonb; rejecting them here keeps the behaviour consistent.
 */
const LONE_SURROGATE = /\p{Cs}/u;

/** True when the string is well-formed UTF-16 (no lone surrogates). */
export function isWellFormedText(value: string): boolean {
  return !LONE_SURROGATE.test(value);
}

/**
 * Required text: trimmed, at least one character, bounded length, well-formed
 * Unicode. An empty or whitespace-only string is rejected rather than stored:
 * a missing value is `null` (via `.nullable()`), never `""`.
 */
export function text(maxLength: number) {
  return z
    .string()
    .trim()
    .min(1)
    .max(maxLength)
    .refine(isWellFormedText, "must be well-formed Unicode (no lone surrogates)");
}

/** A bounded list of short labels (categories, keywords, regions). */
export function labelList() {
  return z.array(text(100)).max(100);
}

const MAX_URL_LENGTH = 2048;

/** Whitespace and ASCII control characters are never part of a stored link. */
// eslint-disable-next-line no-control-regex -- matching control characters is the point.
const URL_FORBIDDEN_CHARS = /[\s\u0000-\u001f\u007f]/;

/**
 * Absolute `https:`/`http:` URL without embedded credentials (docs/SECURITY.md
 * §3). Links are shown to users, so `javascript:`, `data:` and other schemes
 * are rejected. Host/port restrictions for *fetching* belong to the HTTP client
 * (PR-02), not to stored links.
 *
 * Output is the canonical `url.href` (e.g. lower-cased host, percent-encoded
 * path), so what is stored is exactly what was validated — never the raw
 * input. Whitespace/control characters inside the input are rejected rather
 * than encoded, and the length limit applies to the input and to the canonical
 * form (encoding can make it longer).
 */
export const httpUrlSchema = z
  .string()
  .trim()
  .max(MAX_URL_LENGTH)
  .transform((value, ctx) => {
    const fail = (message: string) => {
      ctx.addIssue({ code: "custom", message });
      return z.NEVER;
    };
    if (URL_FORBIDDEN_CHARS.test(value) || !isWellFormedText(value)) {
      return fail("must not contain whitespace, control characters or lone surrogates");
    }
    const url = URL.parse(value);
    if (
      url === null ||
      (url.protocol !== "https:" && url.protocol !== "http:") ||
      url.username !== "" ||
      url.password !== ""
    ) {
      return fail("must be an absolute http(s) URL without credentials");
    }
    if (url.href.length > MAX_URL_LENGTH) {
      return fail(`must be at most ${String(MAX_URL_LENGTH)} characters once normalized`);
    }
    return url.href;
  });

/** Identifier generated by the database (`gen_random_uuid()`). */
export const entityIdSchema = z.uuid();

/** Lower-cased, trimmed e-mail address (RFC 5321 length limit). */
export const emailSchema = z.string().trim().toLowerCase().pipe(z.email().max(254));

/**
 * Parses `value` with `schema`, turning a validation failure into a
 * DomainError("invalid_input") that lists the offending field paths only.
 */
export function parseDomain<T extends z.ZodType>(schema: T, value: unknown): z.output<T> {
  const result = schema.safeParse(value);
  if (result.success) return result.data;
  const fields = [
    ...new Set(result.error.issues.map((issue) => issue.path.map(String).join(".") || "(root)")),
  ];
  throw new DomainError("invalid_input", `Invalid input: ${fields.join(", ")}`, fields);
}
